const W = 474;
const H = 182;

function project([lon, lat]) {
  const x = ((lon + 170) / 350) * W;
  const y = ((78 - lat) / 136) * H;
  return `${x.toFixed(1)},${y.toFixed(1)}`;
}

function polyPath(coords) {
  return 'M ' + coords.map(project).join(' L ') + ' Z';
}

function pointXY(lon, lat) {
  const x = ((lon + 170) / 350) * W;
  const y = ((78 - lat) / 136) * H;
  return { x, y };
}

