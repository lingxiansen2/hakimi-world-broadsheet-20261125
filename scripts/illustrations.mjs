export function renderWorldMapSvg() {
  const graticule = [];
  for (let lon = -150; lon <= 150; lon += 30) {
    const x = ((lon + 170) / 350) * W;
    graticule.push(`<line x1="${x.toFixed(1)}" y1="0" x2="${x.toFixed(1)}" y2="${H}" stroke="#d3ccb8" stroke-width="0.6" stroke-dasharray="2,2"/>`);
  }
  for (let lat = -30; lat <= 60; lat += 30) {
    const y = ((78 - lat) / 136) * H;
    const isEq = lat === 0;
    graticule.push(`<line x1="0" y1="${y.toFixed(1)}" x2="${W}" y2="${y.toFixed(1)}" stroke="${isEq ? '#bdb195' : '#d3ccb8'}" stroke-width="${isEq ? '0.9' : '0.6'}" stroke-dasharray="${isEq ? 'none' : '2,2'}"/>`);
  }

  const landPaths = CONTINENTS.map(
    (c) => `<path d="${polyPath(c)}" fill="#e6dcc4" stroke="#5c503e" stroke-width="1" stroke-linejoin="round"/>`
  ).join('');

  // Conflict / focal rings at Hormuz, Kyiv, Jiuquan, Ituri
  const flashCoords = [
    { lon: 55.5, lat: 26.2, r: 12 },
    { lon: 30.5, lat: 50.4, r: 11 },
    { lon: 100.3, lat: 40.9, r: 11 },
    { lon: 29.9, lat: 1.8, r: 11 },
  ];
  const rings = flashCoords
    .map((f) => {
      const p = pointXY(f.lon, f.lat);
      return `<circle cx="${p.x.toFixed(1)}" cy="${p.y.toFixed(1)}" r="${f.r}" fill="none" stroke="#9b1c1c" stroke-width="1.25" stroke-dasharray="2.5,2" opacity="0.88"/>`;
    })
    .join('');

  // Careful non-overlapping offsets for all 14 sequential pins 1..14
  const offsets = {
    1: [0, -2],
    2: [2, 2],
    3: [2, 4],
    4: [-6, -5],
    5: [-6, 5],
    6: [-12, -5],
    7: [8, -2],
    8: [5, -2],
    9: [-4, -4],
    10: [3, 1],
    11: [0, 0],
    12: [0, 0],
    13: [7, 5],
    14: [0, 0],
  };

  const pins = MAP_PINS.map((pin) => {
    const p = pointXY(pin.lon, pin.lat);
    const [dx, dy] = offsets[pin.id] || [0, 0];
    const cx = Math.min(W - 10, Math.max(10, p.x + dx));
    const cy = Math.min(H - 10, Math.max(10, p.y + dy));
    return `
      <g>
        <circle cx="${cx.toFixed(1)}" cy="${cy.toFixed(1)}" r="7" fill="${pin.color}" stroke="#faf5e8" stroke-width="1.15"/>
        <text x="${cx.toFixed(1)}" y="${(cy + 2.7).toFixed(1)}" text-anchor="middle" font-family="Segoe UI, Arial, sans-serif" font-size="8.2" font-weight="900" fill="#ffffff">${pin.id}</text>
      </g>`;
  }).join('');

  return `
  <svg viewBox="0 0 ${W} ${H}" width="100%" height="100%" xmlns="http://www.w3.org/2000/svg" style="display:block;background:#e8f1f5;border:1.5px solid #5c503e;">
    ${graticule.join('')}
    ${landPaths}
    ${rings}
    <text x="166" y="70" font-family="Georgia, serif" font-size="8.2" font-style="italic" fill="#657e8c" letter-spacing="1.6">ATLANTIC</text>
    <text x="24" y="114" font-family="Georgia, serif" font-size="8.2" font-style="italic" fill="#657e8c" letter-spacing="1.6">PACIFIC</text>
    <text x="322" y="136" font-family="Georgia, serif" font-size="8.2" font-style="italic" fill="#657e8c" letter-spacing="1.6">INDIAN</text>
    ${pins}
    <rect x="5" y="${H - 21}" width="214" height="17" rx="2" fill="#faf5e8" fill-opacity="0.95" stroke="#6f634f" stroke-width="0.8"/>
    <circle cx="15" cy="${H - 12.5}" r="3.8" fill="#9b1c1c"/><text x="22" y="${H - 9.5}" font-family="Segoe UI, Arial" font-size="7.6" font-weight="800" fill="#141210">CRISIS</text>
    <circle cx="68" cy="${H - 12.5}" r="3.8" fill="#16324f"/><text x="75" y="${H - 9.5}" font-family="Segoe UI, Arial" font-size="7.6" font-weight="800" fill="#141210">MARKETS/POL</text>
    <circle cx="148" cy="${H - 12.5}" r="3.8" fill="#1e5b3f"/><text x="155" y="${H - 9.5}" font-family="Segoe UI, Arial" font-size="7.6" font-weight="800" fill="#141210">SCI/OCEANIA</text>
  </svg>`;
}
